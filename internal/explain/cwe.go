// Package explain turns weakness ids (CWE) into plain-language text: what the
// weakness is and what it lets an attacker do. The texts are DepGate's own
// short summaries of the MITRE CWE entries (https://cwe.mitre.org), written for
// developers who do not work in security.
package explain

import (
	"sort"
	"strings"

	"github.com/Ali7Zeynalli/depgate/internal/i18n"
	"github.com/Ali7Zeynalli/depgate/internal/report"
)

type entry struct {
	name, what, risk i18n.T
}

func e(nameAz, nameEn, whatAz, whatEn, riskAz, riskEn string) entry {
	return entry{i18n.T{Az: nameAz, En: nameEn}, i18n.T{Az: whatAz, En: whatEn}, i18n.T{Az: riskAz, En: riskEn}}
}

