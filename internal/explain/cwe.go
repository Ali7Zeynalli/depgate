// Weaknesses explains the CWE ids of one advisory (unknown ids keep their id and a link).
func Weaknesses(ids []string) []report.Weakness {
	seen := map[string]bool{}
	var out []report.Weakness
	for _, id := range ids {
		id = strings.ToUpper(strings.TrimSpace(id))
		if id == "" || seen[id] || id == "NVD-CWE-OTHER" || id == "NVD-CWE-NOINFO" {
			continue
		}
		seen[id] = true
		w := report.Weakness{ID: id, URL: "https://cwe.mitre.org/data/definitions/" + strings.TrimPrefix(id, "CWE-") + ".html"}
		if x, ok := cwes[id]; ok {
			w.Name, w.What, w.Risk = x.name, x.what, x.risk
		}
		out = append(out, w)
	}
	sort.SliceStable(out, func(i, j int) bool { return out[i].Name.En != "" && out[j].Name.En == "" })
	return out
}

// Known reports whether DepGate has a plain-language text for the CWE.
func Known(id string) bool { _, ok := cwes[strings.ToUpper(id)]; return ok }
